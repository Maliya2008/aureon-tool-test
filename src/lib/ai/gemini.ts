export async function understandInput(
  input: string,
  context?: LifeItem[],
  apiKey?: string
): Promise<AIResponse<IntentResult>> {
  const prompt = INTENT_ANALYSIS_PROMPT
    .replace('{input}', input)
    .replace('{context}', context ? `CURRENT CONTEXT:\n${formatItemsForPrompt(context)}` : '')
    .replace('{today}', getToday());

  const result = await callGemini(prompt, { temperature: 0.2 }, apiKey);

  if (!result.success) {
    return { ...result, data: undefined };
  }

  const { data, valid } = validateJSONResponse<IntentResult>(result.data!, {
    intent: input,
    category: 'general',
    entities: [],
    confidence: 0.5,
  });

  return {
    ...result,
    data,
    error: valid ? undefined : 'Response parsing had low confidence. Data may be incomplete.',
  };
}

export async function assessPriority(
  item: LifeItem,
  allItems?: LifeItem[],
  apiKey?: string
): Promise<AIResponse<PriorityAssessment>> {
  const prompt = PRIORITY_ASSESSMENT_PROMPT
    .replace('{item}', JSON.stringify(item, null, 2))
    .replace('{allItems}', allItems ? `ALL ITEMS FOR CONTEXT:\n${formatItemsForPrompt(allItems)}` : '')
    .replace('{today}', getToday());

  const result = await callGemini(prompt, { temperature: 0.1 }, apiKey);

  if (!result.success) {
    return { ...result, data: undefined };
  }

  const { data } = validateJSONResponse<PriorityAssessment>(result.data!, {
    itemId: item.id,
    priority: 'medium',
    reasons: ['Unable to parse priority assessment'],
    urgencyScore: 50,
    financialImpact: 0,
    timeSensitivity: 50,
  });

  return { ...result, data: { ...data, itemId: item.id } };
}

export async function analyzeDocument(
  content: string,
  type?: string,
  apiKey?: string
): Promise<AIResponse<DocumentAnalysis>> {
  const prompt = DOCUMENT_ANALYSIS_PROMPT
    .replace('{content}', content)
    .replace('{type}', type || 'unknown');

  const result = await callGemini(prompt, { temperature: 0.1, maxTokens: 2048 }, apiKey);

  if (!result.success) {
    return { ...result, data: undefined };
  }

  const { data, valid } = validateJSONResponse<DocumentAnalysis>(result.data!, {
    type: 'document',
    title: 'Unknown Document',
    provider: '',
    amount: 0,
    currency: 'USD',
    dueDate: '',
    expirationDate: '',
    summary: 'Unable to analyze document.',
    recommendedAction: 'Please review manually.',
    confidence: 0,
    extractedEntities: [],
  });

  return {
    ...result,
    data,
    error: valid ? undefined : 'Document analysis had low confidence.',
  };
}

export async function generateTasks(
  input: string,
  context?: LifeItem[],
  apiKey?: string
): Promise<AIResponse<TaskGeneration[]>> {
  const prompt = TASK_GENERATION_PROMPT
    .replace('{input}', input)
    .replace('{context}', context ? `CURRENT ITEMS:\n${formatItemsForPrompt(context)}` : '')
    .replace('{today}', getToday());

  const result = await callGemini(prompt, { temperature: 0.3 }, apiKey);

  if (!result.success) {
    return { ...result, data: undefined };
  }

  const { data } = validateJSONResponse<TaskGeneration[]>(result.data!, []);

  return { ...result, data: Array.isArray(data) ? data : [] };
}


// AUREA AI Engine - Gemini Service
// This module handles all communication with the Google Gemini API
// It must run server-side to protect the API key

import {
  SYSTEM_PROMPT,
  INTENT_ANALYSIS_PROMPT,
  PRIORITY_ASSESSMENT_PROMPT,
  DOCUMENT_ANALYSIS_PROMPT,
  TASK_GENERATION_PROMPT,
  INSIGHTS_PROMPT,
  WEEKLY_BRIEFING_PROMPT,
  CHAT_PROMPT,
} from './prompts';

import type {
  EngineConfig,
  AIResponse,
  IntentResult,
  PriorityAssessment,
  DocumentAnalysis,
  TaskGeneration,
  AIInsight,
  WeeklyBriefing,
  LifeItem,
  ChatMessage,
} from './types';

const DEFAULT_CONFIG: EngineConfig = {
  model: 'gemini-2.0-flash',
  temperature: 0.3,
  maxTokens: 4096,
};

// Format date for prompts
function getToday(): string {
  return new Date().toISOString().split('T')[0];
}

// Format items for prompt context
function formatItemsForPrompt(items: LifeItem[]): string {
  if (!items || items.length === 0) return 'No items in context.';
  return items.map(item => JSON.stringify({
    id: item.id,
    type: item.type,
    title: item.title,
    provider: item.provider,
    amount: item.amount,
    currency: item.currency,
    dueDate: item.dueDate,
    expirationDate: item.expirationDate,
    priority: item.priority,
    status: item.status,
  }, null, 2)).join('\n');
}

// Format chat history for prompt
function formatChatHistory(messages: ChatMessage[]): string {
  return messages.map(msg => `[${msg.role.toUpperCase()}]: ${msg.content}`).join('\n\n');
}

// Validate JSON response from Gemini
function validateJSONResponse<T>(raw: string, fallback: T): { data: T; valid: boolean } {
  try {
    // Try to extract JSON from the response
    const jsonMatch = raw.match(/\{[\s\S]*\}|\[[\s\S]*\]/);
    if (!jsonMatch) {
      return { data: fallback, valid: false };
    }
    const parsed = JSON.parse(jsonMatch[0]);
    return { data: parsed as T, valid: true };
  } catch {
    return { data: fallback, valid: false };
  }
}

// Core Gemini API call function
export async function callGemini(
  prompt: string,
  config: Partial<EngineConfig> = {},
  apiKey?: string
): Promise<AIResponse<string>> {
  const startTime = Date.now();
  const finalConfig = { ...DEFAULT_CONFIG, ...config };
  const key = apiKey || getApiKey();

  if (!key) {
    return {
      success: false,
      error: 'GEMINI_API_KEY is not configured. Set it in your environment variables.',
      timestamp: new Date().toISOString(),
    };
  }

  try {
    // Use the Google Generative AI REST API directly
    const url = `https://generativelanguage.googleapis.com/v1beta/models/${finalConfig.model}:generateContent?key=${key}`;

    const requestBody = {
      contents: [
        {
          parts: [{ text: prompt }],
        },
      ],
      generationConfig: {
        temperature: finalConfig.temperature,
        maxOutputTokens: finalConfig.maxTokens,
      },
      systemInstruction: {
        parts: [{ text: finalConfig.systemPrompt || SYSTEM_PROMPT }],
      },
    };

    const response = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(requestBody),
    });

    if (!response.ok) {
      const errorData = await response.json().catch(() => ({}));
      const errorMessage = errorData?.error?.message || `HTTP ${response.status}`;

      if (response.status === 429) {
        return {
          success: false,
          error: 'Rate limit exceeded. Please try again in a moment.',
          timestamp: new Date().toISOString(),
          processingTime: Date.now() - startTime,
        };
      }

      if (response.status === 403) {
        return {
          success: false,
          error: 'API key is invalid or does not have access to this model.',
          timestamp: new Date().toISOString(),
          processingTime: Date.now() - startTime,
        };
      }

      return {
        success: false,
        error: `Gemini API error: ${errorMessage}`,
        timestamp: new Date().toISOString(),
        processingTime: Date.now() - startTime,
      };
    }

    const data = await response.json();
    const text = data?.candidates?.[0]?.content?.parts?.[0]?.text;

    if (!text) {
      return {
        success: false,
        error: 'No response generated by the model.',
        timestamp: new Date().toISOString(),
        processingTime: Date.now() - startTime,
      };
    }

    return {
      success: true,
      data: text,
      model: finalConfig.model,
      timestamp: new Date().toISOString(),
      processingTime: Date.now() - startTime,
    };
  } catch (error) {
    const message = error instanceof Error ? error.message : 'Unknown error';

    if (message.includes('timeout') || message.includes('aborted')) {
      return {
        success: false,
        error: 'Request timed out. Please try again.',
        timestamp: new Date().toISOString(),
        processingTime: Date.now() - startTime,
      };
    }

    return {
      success: false,
      error: `Failed to communicate with Gemini: ${message}`,
      timestamp: new Date().toISOString(),
      processingTime: Date.now() - startTime,
    };
  }
}

// Get API key from environment (server-side only)
function getApiKey(): string | undefined {
  // In server context, use process.env
  if (typeof process !== 'undefined' && process.env?.GEMINI_API_KEY) {
    return process.env.GEMINI_API_KEY;
  }
  return undefined;
}

